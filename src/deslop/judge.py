# ABOUTME: LLM judges: a document-level pairwise comparison on four named items that gates apply,
# ABOUTME: the paragraph comparison used for judge calibration, and an absolute 1-5 rubric kept
# ABOUTME: as a secondary trend score. All are cached like any provider call.
from __future__ import annotations

import hashlib
import json
import random
from typing import Any

from pydantic import BaseModel, Field

from deslop.providers.base import CachingProvider, ProviderError
from deslop.report import JudgeScores
from deslop.voice.model import Voice

JUDGE_SYSTEM = """You are a demanding editor who knows one writer's voice from a description
and two verbatim samples. Score a paragraph on three rubrics, each 1 to 5, and answer in
JSON only.

voice: how far the paragraph reads as this writer. 5 = could be lifted from the samples;
3 = competent but generic; 1 = nothing of the voice.
model_prose: how far it reads as prose generated by a language model: balanced antitheses,
tidy triads, aphoristic closes, "not X but Y" frames, text treated as an agent, summarising
last sentences, even cadence. 5 = unmistakably model prose; 1 = no sign of it.
fidelity: how faithfully it keeps the listed propositions, no more and no fewer. 5 = all kept,
nothing added; 1 = meaning changed.

Return exactly: {"voice": n, "model_prose": n, "fidelity": n, "note": "one sentence"}"""

COMPARE_SYSTEM = """You are a demanding editor who knows one writer's voice from a description
and two verbatim samples of it. You are shown two paragraphs, A and B, on the same subject.
Decide which of the two reads more like the writer of the samples, and which reads more like
prose generated by a language model (balanced antitheses, tidy triads, aphoristic closes,
"not X but Y" frames, text treated as an agent, summarising last sentences, even cadence).
Judge the prose, not the subject, and not length. Give your confidence in the first answer
from 0.5 (a coin toss) to 1.0 (certain). Answer in JSON only:

{"more_like_writer": "A" or "B", "more_like_model": "A" or "B", "confidence": 0.5-1.0,
"note": "one sentence naming what decided it"}"""

DOCUMENT_SYSTEM = """You are a demanding editor who knows one writer's voice from a description
and two verbatim samples of it. You are shown the original of a piece and two versions of it,
TEXT A and TEXT B (one of them may be the original itself). Answer four questions separately,
each with "A", "B" or "tie":

voice: which reads more like the writer of the samples (judge the prose, not the subject or
the length).
coherent: in which does each sentence follow from the last, with every pronoun and "this"
pointing at something already said.
tense_person: which keeps a consistent tense and grammatical person throughout.
order: which better preserves the order and emphasis of the argument's content. The presence
or absence of a title, headings and lists is not part of this item.

Give your confidence in the answers as a whole from 0.5 (a coin toss) to 1.0 (certain).
Answer in JSON only:

{"voice": "A"|"B"|"tie", "coherent": "A"|"B"|"tie", "tense_person": "A"|"B"|"tie",
"order": "A"|"B"|"tie", "confidence": 0.5-1.0, "note": "one sentence naming what decided it"}"""

JUDGE_ITEMS = ("voice", "coherent", "tense_person", "order")
GATE_CONFIDENCE = 0.7
CALIBRATION_MIN_ACCURACY = 0.8


class PairVerdict(BaseModel):
    """One pairwise judgement of a candidate against another text: whether the candidate was
    picked as more like the writer, whether it was picked as more like model prose, and the
    judge's confidence. `shown_as` is the letter the candidate had."""

    against: str  # "original" | "candidate k"
    wins: bool
    picked_as_model: bool
    confidence: float
    shown_as: str = "A"
    provider: str = ""
    model: str = ""
    note: str = ""


class DocumentVerdict(BaseModel):
    """One document-level comparison of a candidate against another text, answered item by
    item: `items` maps each of `JUDGE_ITEMS` to win, tie or loss from the candidate's side."""

    against: str  # "original" | "candidate k"
    items: dict[str, str] = Field(default_factory=dict)
    confidence: float = 0.5
    shown_as: str = "A"
    provider: str = ""
    model: str = ""
    note: str = ""

    @property
    def wins(self) -> int:
        return sum(1 for v in self.items.values() if v == "win")

    @property
    def losses(self) -> int:
        return sum(1 for v in self.items.values() if v == "loss")

    @property
    def net(self) -> int:
        return self.wins - self.losses

    @property
    def no_loss(self) -> bool:
        """The acceptance rule against the original: a win or a tie on every item."""
        return self.losses == 0

    def flipped(self, against: str) -> DocumentVerdict:
        """The same verdict seen from the other text's side."""
        swap = {"win": "loss", "loss": "win", "tie": "tie"}
        return DocumentVerdict(
            against=against,
            items={k: swap[v] for k, v in self.items.items()},
            confidence=self.confidence,
            shown_as="B" if self.shown_as == "A" else "A",
            provider=self.provider,
            model=self.model,
            note=self.note,
        )


class JudgeCalibration(BaseModel):
    """How well a provider told held-out corpus paragraphs from LLM-reference paragraphs when
    used as the comparative judge; stored in voice.yaml and read by apply."""

    provider: str
    model: str
    pairs: int
    accuracy: float  # share of pairs where the corpus paragraph was picked as the writer's
    model_prose_accuracy: float  # share where the LLM paragraph was picked as model prose
    mean_confidence: float
    position_bias: float = 0.0  # share of "A" picks minus 0.5

    @property
    def usable(self) -> bool:
        return self.accuracy >= CALIBRATION_MIN_ACCURACY


def _order(candidate: str, other: str) -> bool:
    """Deterministic order so the cache answers repeats: True when the candidate is shown as A."""
    digest = hashlib.sha256((candidate + "\x00" + other).encode("utf-8")).digest()
    return digest[0] % 2 == 0


STRICT_FORMAT = (
    "\n\nYour previous answer was not valid JSON. Reply with the JSON object only: no prose, "
    "no code fence, double quotes around every key and string value."
)


def _complete_json(
    provider: CachingProvider, system: str, user: str
) -> tuple[dict[str, Any] | None, Any]:
    """Ask once; on a JSON parse failure ask again with a stricter format instruction. Both
    calls are cached. Returns the parsed object (None if both failed) and the completion."""
    completion = provider.complete(system, user, temperature=0.0)
    try:
        return _json_object(completion.text), completion
    except (ValueError, json.JSONDecodeError):
        pass
    completion = provider.complete(system + STRICT_FORMAT, user, temperature=0.0)
    try:
        return _json_object(completion.text), completion
    except (ValueError, json.JSONDecodeError):
        return None, completion


def _json_object(text: str) -> dict[str, Any]:
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end < start:
        raise ValueError("no JSON object in response")
    data = json.loads(text[start : end + 1])
    if not isinstance(data, dict):
        raise ValueError("response is not a JSON object")
    return data


def _pick(value: object) -> str:
    v = str(value).strip().upper()[:1]
    return v if v in ("A", "B") else ""


def _confidence(value: object) -> float:
    try:
        c = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 0.5
    return max(0.5, min(1.0, c))


def compare(
    candidate: str,
    other: str,
    voice: Voice,
    provider: CachingProvider,
    *,
    exemplars: list[str],
    against: str = "original",
) -> PairVerdict:
    """Ask `provider` which of `candidate` and `other` reads more like the voice's writer and
    which more like model prose. The pair is shown in a deterministic order; the verdict is
    reported from the candidate's side. `provider` must not have written the candidate."""
    candidate_is_a = _order(candidate, other)
    a, b = (candidate, other) if candidate_is_a else (other, candidate)
    samples = "\n\n".join(f"SAMPLE {i}:\n{e.strip()}" for i, e in enumerate(exemplars[:2], 1))
    user = (
        f"THE VOICE:\n{voice.profile.strip()}\n\n{samples or '(no samples available)'}\n\n"
        f"PARAGRAPH A:\n{a.strip()}\n\nPARAGRAPH B:\n{b.strip()}"
    )
    data, completion = _complete_json(provider, COMPARE_SYSTEM, user)
    if data is not None:
        writer_pick = _pick(data.get("more_like_writer"))
        model_pick = _pick(data.get("more_like_model"))
        confidence = _confidence(data.get("confidence"))
        note = str(data.get("note", ""))[:300]
    else:
        writer_pick, model_pick, confidence, note = "", "", 0.5, "judge gave no JSON"
    mine = "A" if candidate_is_a else "B"
    return PairVerdict(
        against=against,
        wins=writer_pick == mine,
        picked_as_model=model_pick == mine,
        confidence=confidence,
        shown_as=mine,
        provider=completion.provider,
        model=completion.model,
        note=note,
    )


def compare_with(
    candidate: str,
    other: str,
    voice: Voice,
    judges: list[CachingProvider],
    *,
    exemplars: list[str],
    against: str = "original",
) -> PairVerdict:
    """One verdict from one or more judges. With several (when no single provider is clear of
    both writers) the candidate wins only if every judge picks it, and the confidence is the
    mean; one judge is the usual case."""
    verdicts = [
        compare(candidate, other, voice, j, exemplars=exemplars, against=against) for j in judges
    ]
    if len(verdicts) == 1:
        return verdicts[0]
    return PairVerdict(
        against=against,
        wins=all(v.wins for v in verdicts),
        picked_as_model=any(v.picked_as_model for v in verdicts),
        confidence=round(sum(v.confidence for v in verdicts) / len(verdicts), 3),
        shown_as=verdicts[0].shown_as,
        provider="+".join(v.provider for v in verdicts),
        model="+".join(v.model for v in verdicts),
        note=" / ".join(v.note for v in verdicts if v.note)[:300],
    )


def compare_document(
    candidate: str,
    other: str,
    original: str,
    voice: Voice,
    provider: CachingProvider,
    *,
    exemplars: list[str],
    against: str = "original",
) -> DocumentVerdict:
    """Ask `provider` to compare `candidate` with `other` on the four `JUDGE_ITEMS`, with
    `original` shown as the reference for order and emphasis. The pair is shown in a
    deterministic order; the verdict is reported from the candidate's side. `provider` must
    not have written the candidate."""
    candidate_is_a = _order(candidate, other)
    a, b = (candidate, other) if candidate_is_a else (other, candidate)
    samples = "\n\n".join(f"SAMPLE {i}:\n{e.strip()}" for i, e in enumerate(exemplars[:2], 1))
    user = (
        f"THE VOICE:\n{voice.profile.strip()}\n\n{samples or '(no samples available)'}\n\n"
        f"THE ORIGINAL:\n{original.strip()}\n\nTEXT A:\n{a.strip()}\n\nTEXT B:\n{b.strip()}"
    )
    data, completion = _complete_json(provider, DOCUMENT_SYSTEM, user)
    mine = "A" if candidate_is_a else "B"
    items: dict[str, str] = {}
    if data is not None:
        for item in JUDGE_ITEMS:
            pick = str(data.get(item, "")).strip().lower()[:3]
            if pick == "tie":
                items[item] = "tie"
            elif pick[:1].upper() in ("A", "B"):
                items[item] = "win" if pick[:1].upper() == mine else "loss"
            else:
                items[item] = "loss"
        confidence = _confidence(data.get("confidence"))
        note = str(data.get("note", ""))[:300]
    else:
        items = dict.fromkeys(JUDGE_ITEMS, "loss")
        confidence, note = 0.5, "judge gave no JSON"
    return DocumentVerdict(
        against=against,
        items=items,
        confidence=confidence,
        shown_as=mine,
        provider=completion.provider,
        model=completion.model,
        note=note,
    )


def document_win_rate(verdicts: list[DocumentVerdict]) -> float | None:
    """Share of comparisons the candidate came out ahead in: a net win counts 1, a draw 0.5."""
    if not verdicts:
        return None
    points = sum(1.0 if v.net > 0 else 0.5 if v.net == 0 else 0.0 for v in verdicts)
    return round(points / len(verdicts), 3)


def win_rate(pairs: list[PairVerdict]) -> float | None:
    if not pairs:
        return None
    return round(sum(1 for p in pairs if p.wins) / len(pairs), 3)


def beats_original(pairs: list[PairVerdict], min_confidence: float = GATE_CONFIDENCE) -> bool:
    """The acceptance gate: picked over the original with at least `min_confidence`."""
    return any(p.against == "original" and p.wins and p.confidence >= min_confidence for p in pairs)


def calibrate_judge(
    voice: Voice,
    provider: CachingProvider,
    llm_paragraphs: list[str],
    corpus_paragraphs: list[str],
    *,
    exemplars: list[str],
    pairs: int = 100,
    seed: int = 0,
) -> JudgeCalibration:
    """Measure `provider` as the comparative judge on `pairs` pairs of one LLM-reference
    paragraph and one held-out corpus paragraph: accuracy is how often the corpus paragraph
    was picked as the writer's. Pairs are drawn with `seed`, so the cache answers reruns."""
    rng = random.Random(seed)
    llm = list(llm_paragraphs)
    corpus = list(corpus_paragraphs)
    rng.shuffle(llm)
    rng.shuffle(corpus)
    count = min(pairs, len(llm), len(corpus))
    if count == 0:
        raise ValueError("calibration needs at least one paragraph of each kind")
    correct = model_correct = 0
    confidence = 0.0
    a_picks = 0
    model_name = provider.default_model
    for i in range(count):
        try:
            v = compare(corpus[i], llm[i], voice, provider, exemplars=exemplars, against="llm")
        except ProviderError:
            continue
        model_name = v.model or model_name
        correct += v.wins
        model_correct += not v.picked_as_model
        confidence += v.confidence
        a_picks += (v.shown_as == "A") == v.wins
    return JudgeCalibration(
        provider=provider.name,
        model=model_name,
        pairs=count,
        accuracy=round(correct / count, 3),
        model_prose_accuracy=round(model_correct / count, 3),
        mean_confidence=round(confidence / count, 3),
        position_bias=round(a_picks / count - 0.5, 3),
    )


# ---------------------------------------------------------------- absolute rubric (secondary)


def judge_paragraph(
    paragraph: str,
    voice: Voice,
    provider: CachingProvider,
    *,
    exemplars: list[str],
    propositions: list[str] | None = None,
) -> JudgeScores:
    """Absolute 1-5 rubric scores for trend tracking; not a gate. `provider` should not be
    the provider that wrote the paragraph."""
    samples = "\n\n".join(f"SAMPLE {i}:\n{e.strip()}" for i, e in enumerate(exemplars[:2], 1))
    props = "\n".join(f"{i}. {p}" for i, p in enumerate(propositions or [], 1)) or "(none listed)"
    user = (
        f"THE VOICE:\n{voice.profile.strip()}\n\n{samples or '(no samples available)'}\n\n"
        f"PROPOSITIONS THE PARAGRAPH MUST KEEP:\n{props}\n\nPARAGRAPH:\n{paragraph.strip()}"
    )
    completion = provider.complete(JUDGE_SYSTEM, user, temperature=0.0)
    text = completion.text
    try:
        data = _json_object(text)
        v = _clamp(data.get("voice"))
        m = _clamp(data.get("model_prose"))
        f = _clamp(data.get("fidelity"))
        note = str(data.get("note", ""))[:300]
    except (ValueError, AttributeError, json.JSONDecodeError):
        v, m, f, note = 1, 5, 1, "judge gave no JSON"
    overall = round((v + (6 - m) + f) / 3.0, 2)
    return JudgeScores(
        voice=v,
        model_prose=m,
        fidelity=f,
        overall=overall,
        provider=completion.provider,
        model=completion.model,
        note=note,
    )


def _clamp(value: object) -> int:
    try:
        n = int(round(float(value)))  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 1
    return max(1, min(5, n))


